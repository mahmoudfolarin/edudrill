// Generates requested number of random questions for a subject
export const getOfflineQuestions = (subject, count = 50) => {
  const lookupSubject = subject === "use-of-english" ? "english-language" : subject;
  const bank = sampleQuestions[lookupSubject] || sampleQuestions["default"];
  const results = [];
  for (let i = 0; i < count; i++) {
    const randomIdx = Math.floor(Math.random() * bank.length);
    const q = bank[randomIdx];
    
    // Slight variation to make options look different if repeated
    const shuffledOptions = [...q.options].sort(() => Math.random() - 0.5);
    
    results.push({
      id: `${subject}-${Date.now()}-${i}`,
      question: q.question,
      options: shuffledOptions,
      answer: q.answer
    });
  }
  return results;
};
